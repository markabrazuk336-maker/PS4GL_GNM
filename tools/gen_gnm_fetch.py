"""gen_gnm_fetch.py — vertex fetch shaders for the driver.

    python tools/gen_gnm_fetch.py

Writes src/gen/ps4gl_fetch.h: GCN machine code for 1..16 vertex attributes.
Convention (the same as shaders from tools/shadersbC.py): V# table in s[2:3], 16 bytes per
attribute, attribute k -> v[4+4k : 7+4k], return through s[0:1]. Every V# is loaded into
the same s[12:15], so the fetch shader never touches SGPRs above s15.
"""
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gcnasm  # noqa: E402


def main():
    out = ['// Generated by tools/gen_gnm_fetch.py. Do not edit.',
           '// V# table in s[2:3] (16 bytes per attribute), attribute k -> v[4+4k : 7+4k], return through s[0:1].']
    arrs = []
    with tempfile.TemporaryDirectory() as tmp:
        for n in range(1, 17):
            lines = []
            for k in range(n):
                lines.append('s_load_dwordx4 s[12:15], s[2:3], %d' % (4 * k))
                lines.append('s_waitcnt lgkmcnt(0)')
                lines.append('buffer_load_format_xyzw v[%d:%d], v0, s[12:15], 0 idxen' % (4 + 4 * k, 7 + 4 * k))
            lines += ['s_waitcnt vmcnt(0)', 's_setpc_b64 s[0:1]']
            p = Path(tmp) / ('f%d.s' % n)
            p.write_text('\n'.join(lines) + '\n')
            b = gcnasm.assemble(p)
            out.append('static const unsigned char g_fetch%d[] = { %s };' % (n, ', '.join('0x%02x' % x for x in b)))
            arrs.append('{ g_fetch%d, sizeof( g_fetch%d ) }' % (n, n))
    out.append('static const struct { const unsigned char *code; unsigned size; } g_fetch[17] = { { 0, 0 }, %s };'
               % ', '.join(arrs))
    # DRAW_INDEX_2 hangs the PS4 GPU, so indexed draws use DRAW_INDEX_AUTO and the fetch
    # shader reads the index itself: the index buffer V# is table entry n (right after the
    # attributes), the index replaces v0, and attributes are then loaded by it.
    out.append('// Indexed: the index buffer V# is table entry n (after the attributes), index -> v0.')
    for bits in (16, 32):
        arrs = []
        with tempfile.TemporaryDirectory() as tmp:
            for n in range(1, 17):
                lines = ['s_load_dwordx4 s[12:15], s[2:3], %d' % (4 * n),
                         'v_lshlrev_b32 v1, %d, v0' % (1 if bits == 16 else 2),
                         's_waitcnt lgkmcnt(0)',
                         '%s v0, v1, s[12:15], 0 offen' % ('buffer_load_ushort' if bits == 16 else 'buffer_load_dword'),
                         's_waitcnt vmcnt(0)']
                for k in range(n):
                    lines.append('s_load_dwordx4 s[12:15], s[2:3], %d' % (4 * k))
                    lines.append('s_waitcnt lgkmcnt(0)')
                    lines.append('buffer_load_format_xyzw v[%d:%d], v0, s[12:15], 0 idxen' % (4 + 4 * k, 7 + 4 * k))
                lines += ['s_waitcnt vmcnt(0)', 's_setpc_b64 s[0:1]']
                p = Path(tmp) / ('i%d_%d.s' % (bits, n))
                p.write_text('\n'.join(lines) + '\n')
                b = gcnasm.assemble(p)
                out.append('static const unsigned char g_fetchI%d_%d[] = { %s };' % (bits, n, ', '.join('0x%02x' % x for x in b)))
                arrs.append('{ g_fetchI%d_%d, sizeof( g_fetchI%d_%d ) }' % (bits, n, bits, n))
        out.append('static const struct { const unsigned char *code; unsigned size; } g_fetchI%d[17] = { { 0, 0 }, %s };'
                   % (bits, ', '.join(arrs)))
    dst = ROOT / 'src' / 'gen' / 'ps4gl_fetch.h'
    dst.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\n')
    print('written:', dst)


if __name__ == '__main__':
    main()
