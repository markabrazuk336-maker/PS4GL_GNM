"""gen_heap.py — malloc for PS4 on top of direct memory (src/ps4gl_heap.c).

    python tools/gen_heap.py path/to/SDL2/src/stdlib/SDL_malloc.c

The stock malloc takes flexible memory, and a game only has about 300 MiB of it. This
generator takes dlmalloc 2.8.3 by Doug Lea (public domain, the copy that ships inside SDL2)
and puts it on a large block of direct memory. Our malloc/free/... win over malloc.lo from
libc.a, so libc and libc++ use them too.

The result is committed to the repository, so SDL2 is only needed to regenerate it.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "ps4gl_heap.c")

if len(sys.argv) != 2:
    raise SystemExit(__doc__)
lines = open(sys.argv[1], encoding="utf-8", errors="replace").read().split("\n")
# only dlmalloc itself, without the SDL wrappers around it
first = next(i for i, l in enumerate(lines) if "This is a version (aka dlmalloc)" in l) - 1
last = next(i for i, l in enumerate(lines) if l.startswith("#endif /* !HAVE_MALLOC */"))
body = lines[first:last]
text = "\n".join(body)
for old in ("#ifndef memset\n#define memset  SDL_memset\n#endif\n",
            "#ifndef memcpy\n#define memcpy  SDL_memcpy\n#endif\n"):
    assert old in text, old
    text = text.replace(old, "")
# locks: pthread mutexes crash this early on PS4 (SIGBUS in libkernel), so use a spin lock
PT = """#include <pthread.h>
#define MLOCK_T pthread_mutex_t
#define INITIAL_LOCK(l)      pthread_mutex_init(l, NULL)
#define ACQUIRE_LOCK(l)      pthread_mutex_lock(l)
#define RELEASE_LOCK(l)      pthread_mutex_unlock(l)

#if HAVE_MORECORE
static MLOCK_T morecore_mutex = PTHREAD_MUTEX_INITIALIZER;
#endif /* HAVE_MORECORE */

static MLOCK_T magic_init_mutex = PTHREAD_MUTEX_INITIALIZER;
"""
SPIN = """int scePthreadYield( void );
#define MLOCK_T volatile int
static int ps4gl_spin_lock( volatile int *l )
{
	int n = 0;
	while ( __atomic_exchange_n( l, 1, __ATOMIC_ACQUIRE ) )
	{
		while ( *l )
		{
			if ( ++n < 64 ) __builtin_ia32_pause();
			else { n = 0; scePthreadYield(); }
		}
	}
	return 0;
}
#define INITIAL_LOCK(l)      ( *(l) = 0 )
#define ACQUIRE_LOCK(l)      ps4gl_spin_lock(l)
#define RELEASE_LOCK(l)      __atomic_store_n( (l), 0, __ATOMIC_RELEASE )

#if HAVE_MORECORE
static MLOCK_T morecore_mutex = 0;
#endif /* HAVE_MORECORE */

static MLOCK_T magic_init_mutex = 0;
"""
assert PT in text
text = text.replace(PT, SPIN)
assert "SDL_" not in text, [l for l in text.split("\n") if "SDL_" in l][:5]

HEAD = r'''/* PS4GL_GNM: malloc for PS4 — GENERATED by tools/gen_heap.py, do not edit.
 * dlmalloc 2.8.3 (Doug Lea, public domain) on top of direct memory. See THIRD_PARTY.md. */
#include <sys/types.h>
#include <stddef.h>
#include <stdint.h>
#include <string.h>
#include <errno.h>
#include <stdlib.h>

/* ---- where the memory comes from ---- */
int32_t sceKernelAllocateDirectMemory( off_t searchStart, off_t searchEnd, size_t len, size_t align, int32_t type, off_t *physOut );
int32_t sceKernelMapDirectMemory( void **addr, size_t len, int32_t prot, int32_t flags, off_t directMemoryStart, size_t align );
int32_t sceKernelMapFlexibleMemory( void **addr, size_t len, int32_t prot, int flags );
size_t sceKernelGetDirectMemorySize( void );

#ifndef PS4GL_HEAP_DIRECT_BYTES
#define PS4GL_HEAP_DIRECT_BYTES ( (size_t)1536 << 20 )	/* how much direct memory the heap takes */
#endif

static char *s_heapTop, *s_heapEnd;
static int s_heapInitDone;

static void HeapInit( void )
{
	s_heapInitDone = 1;
	size_t total = sceKernelGetDirectMemorySize();
	size_t want = PS4GL_HEAP_DIRECT_BYTES;
	if ( total < want ) return;
	off_t phys = 0;
	void *mem = NULL;
	int r = sceKernelAllocateDirectMemory( 0, (off_t)total, want, 0x200000, 0 /* WB_ONION: CPU cached */, &phys );
	if ( r >= 0 ) r = sceKernelMapDirectMemory( &mem, want, 3 /* CPU read+write */, 0, phys, 0x200000 );
	if ( r < 0 || !mem ) return;
	s_heapTop = (char *)mem;
	s_heapEnd = s_heapTop + want;
}

/* like sbrk: inc == 0 returns the current end; blocks need not be contiguous (MORECORE_CONTIGUOUS 0) */
static void *ps4gl_morecore( intptr_t inc )
{
	if ( !s_heapInitDone ) HeapInit();
	if ( inc == 0 ) return s_heapTop ? s_heapTop : (void *)0;
	if ( inc < 0 ) return (void *)~(size_t)0;
	if ( !s_heapTop || s_heapTop + inc > s_heapEnd )
	{
		/* direct memory is used up (or absent): take a block of flexible memory */
		size_t sz = (size_t)inc < ( (size_t)32 << 20 ) ? ( (size_t)32 << 20 ) : ( ( (size_t)inc + 0x3FFF ) & ~(size_t)0x3FFF );
		void *m = NULL;
		if ( sceKernelMapFlexibleMemory( &m, sz, 3, 0 ) < 0 || !m ) return (void *)~(size_t)0;
		s_heapTop = (char *)m;
		s_heapEnd = s_heapTop + sz;
	}
	char *p = s_heapTop;
	s_heapTop += inc;
	return p;
}

#define USE_DL_PREFIX
#define MALLOC_ALIGNMENT ( (size_t)16U )	/* 2.8.3 defaults to 8, and SSE (movaps) then crashes */
#define USE_LOCKS 1
#define HAVE_MMAP 0
#define HAVE_MREMAP 0
#define HAVE_MORECORE 1
#define MORECORE ps4gl_morecore
#define MORECORE_CONTIGUOUS 0
#define MORECORE_CANNOT_TRIM 1
#define NO_MALLINFO 1
#define malloc_getpagesize ( (size_t)16384 )
#define DEFAULT_GRANULARITY ( (size_t)4 << 20 )
#define LACKS_SYS_MMAN_H
#define LACKS_SYS_PARAM_H
'''

TAIL = r'''

/* ---- the real names: these replace malloc.lo and friends from libc.a ---- */
void *malloc( size_t n ) { return dlmalloc( n ); }
void free( void *p ) { if ( p ) dlfree( p ); }
void *calloc( size_t a, size_t b ) { return dlcalloc( a, b ); }
void *realloc( void *p, size_t n ) { return dlrealloc( p, n ); }
void *memalign( size_t al, size_t n ) { return dlmemalign( al, n ); }
void *__memalign( size_t al, size_t n ) { return dlmemalign( al, n ); }
void *aligned_alloc( size_t al, size_t n ) { return dlmemalign( al, n ); }
void *valloc( size_t n ) { return dlmemalign( 16384, n ); }
int posix_memalign( void **out, size_t al, size_t n )
{
	if ( al < sizeof( void * ) || ( al & ( al - 1 ) ) ) return EINVAL;
	void *p = dlmemalign( al, n );
	if ( !p && n ) return ENOMEM;
	*out = p;
	return 0;
}
size_t malloc_usable_size( void *p ) { return p ? dlmalloc_usable_size( p ) : 0; }
'''

open(OUT, "w", encoding="utf-8", newline="\n").write(HEAD + text + TAIL)
print("written:", OUT, len(text.split("\n")), "lines of dlmalloc")
