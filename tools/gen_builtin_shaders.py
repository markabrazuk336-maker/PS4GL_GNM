"""gen_builtin_shaders.py — the driver's own small shaders (blit and clear).

    python tools/gen_builtin_shaders.py

Assembles shaders/builtin/*.s and writes src/gen/ps4gl_builtin_shaders.h.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import gcnasm  # noqa: E402

SHADERS = (("g_blitVs", "blit_vs.s"), ("g_blitPs", "blit_ps.s"), ("g_clearPs", "clear_ps.s"))


def main():
    out = ["// Generated by tools/gen_builtin_shaders.py from shaders/builtin/*.s. Do not edit."]
    for name, fn in SHADERS:
        code = gcnasm.assemble(ROOT / "shaders" / "builtin" / fn)
        out.append("static const unsigned char %s[] = { %s };" % (name, ", ".join("0x%02x" % b for b in code)))
    dst = ROOT / "src" / "gen" / "ps4gl_builtin_shaders.h"
    dst.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("written:", dst)


if __name__ == "__main__":
    main()
