"""build.py — build the sample into an installable .pkg.

    python build.py            # build/cube/IV0000-PSGL00001_00-PS4GLCUBE0000000.pkg
    python build.py --no-pkg   # stop after the ELF (no .NET needed)

Needs: Python 3.8+, LLVM on PATH (clang, clang++, ld.lld, llc, opt, llvm-link, llvm-objcopy,
llvm-mc, with the AMDGPU target; tested with LLVM 19.1), and OO_PS4_TOOLCHAIN pointing at
the OpenOrbis PS4 Toolchain.
"""
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "build", "cube")
SAMPLE = os.path.join(ROOT, "samples", "cube")
LIBS = ["-lc", "-lkernel", "-lc++", "-lSceSysmodule", "-lSceSystemService", "-lSceVideoOut", "-lSceGnmDriver"]
SHADERS = ("color.vert", "color.frag", "cube.vert", "cube.frag")


def tool(name):
    path = shutil.which(name)
    if not path:
        raise SystemExit("%s not found: install LLVM and add it to PATH" % name)
    return path


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if r.returncode:
        print(r.stdout[-4000:], r.stderr[-6000:])
        raise SystemExit("failed: " + os.path.basename(cmd[0]))
    return r.stdout


def compile_shaders(gen):
    """GLSL -> .sb -> one C header, so the sample does not need to read files at run time."""
    lines = ["// Generated by build.py. Do not edit."]
    for fn in SHADERS:
        sb = os.path.join(OUT, "shaders", fn + ".sb")
        os.makedirs(os.path.dirname(sb), exist_ok=True)
        run([sys.executable, os.path.join(ROOT, "tools", "shadersbC.py"), os.path.join(SAMPLE, "shaders", fn), "-o", sb])
        with open(sb, "rb") as f:
            data = f.read()
        lines.append("static const unsigned char g_%s[] = { %s };" % (fn.replace(".", "_"), ",".join(str(b) for b in data)))
        print("  shader %-11s %6d bytes" % (fn, len(data)))
    with open(os.path.join(gen, "sample_shaders.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main():
    tc = os.environ.get("OO_PS4_TOOLCHAIN")
    if not tc or not os.path.isdir(tc):
        raise SystemExit("set OO_PS4_TOOLCHAIN to the OpenOrbis PS4 Toolchain folder")
    gen, obj = os.path.join(OUT, "gen"), os.path.join(OUT, "obj")
    os.makedirs(gen, exist_ok=True)
    os.makedirs(obj, exist_ok=True)

    print("1. shaders")
    compile_shaders(gen)

    print("2. code")
    base = ["--target=x86_64-pc-freebsd12-elf", "-fPIC", "-funwind-tables", "-O2", "-D_GNU_SOURCE",
            "-isysroot", tc, "-isystem", os.path.join(tc, "include"),
            "-I", os.path.join(ROOT, "include"), "-I", os.path.join(ROOT, "src"), "-I", gen]
    cxx = base + ["-std=c++17", "-isystem", os.path.join(tc, "include", "c++", "v1")]
    objs = []
    for src, cc, flags in ((os.path.join(ROOT, "src", "ps4gl.cpp"), "clang++", cxx),
                           (os.path.join(ROOT, "src", "ps4gl_heap.c"), "clang", base + ["-w"]),
                           (os.path.join(SAMPLE, "main.cpp"), "clang++", cxx)):
        o = os.path.join(obj, os.path.basename(src) + ".o")
        run([tool(cc)] + flags + ["-c", src, "-o", o])
        objs.append(o)

    print("3. link")
    elf = os.path.join(OUT, "cube.elf")
    run([tool("ld.lld"), "-m", "elf_x86_64", "-pie", "--script", os.path.join(tc, "link.x"), "--eh-frame-hdr",
         "-o", elf, "-L" + os.path.join(tc, "lib")] + objs + LIBS + [os.path.join(tc, "lib", "crt1.o")])
    print("  %s (%d KiB)" % (elf, os.path.getsize(elf) // 1024))
    if "--no-pkg" in sys.argv:
        return 0

    print("4. package")
    r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "mkpkg.py"), elf, "--title", "PS4GL Cube",
                        "--title-id", "PSGL00001", "--label", "PS4GLCUBE", "-o", OUT])
    return r.returncode


if __name__ == "__main__":
    sys.exit(main())
